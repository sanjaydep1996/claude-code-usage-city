"""Executive Value Report Generator for DevCity.

Produces clean, shareable Markdown and JSON reports (DEVCITY_REPORT.md)
highlighting headline dollar savings, AI Health Grade, and project ROI.
"""

import datetime as dt
import json
import pathlib
from typing import Dict, Any, Optional

from .health import calculate_health_score


def generate_markdown_report(payload: Dict[str, Any]) -> str:
    """Generates an executive markdown value report from aggregated data."""
    t = payload.get("totals", {})
    health = calculate_health_score(payload)
    projects = payload.get("projects", [])

    cost = t.get("costUSD", 0.0)
    saved = t.get("costSavedUSD", 0.0)
    total_val = cost + saved
    pct_saved = (saved / total_val * 100.0) if total_val > 0 else 0.0
    tokens = t.get("tokens", {})
    total_tokens = sum(tokens.values())

    date_str = dt.datetime.now().strftime("%Y-%m-%d")

    lines = [
        f"# DevCity AI Value & Observability Report",
        f"*Generated on {date_str} · Privacy Mode: 100% Local-First*",
        "",
        "---",
        "",
        f"## 🎯 Headline Value: Caching Saved ~${saved:,.2f} ({pct_saved:.1f}% Cost Reduction)",
        f"> **AI Health Grade: {health.grade} ({health.score}/100)**  ",
        f"> Total API Spend: **${cost:,.2f}** · Active Time: **{t.get('activeHours', 0.0):.1f} hours** · Total Tokens: **{total_tokens:,}**",
        "",
        "---",
        "",
        "## 💡 Top 3 Actionable AI Efficiency Tips",
    ]

    for idx, tip in enumerate(health.top_tips, start=1):
        lines.append(f"{idx}. {tip}")

    lines.extend([
        "",
        "---",
        "",
        "## 📊 Top Projects by API Spend & Cache Efficiency",
        "",
        "| Project | API Cost | Active Hours | Cache Hit % | Cache Savings | Status |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ])

    sorted_projects = sorted(projects, key=lambda p: p.get("costUSD", 0.0), reverse=True)
    for p in sorted_projects[:10]:
        leak_icon = "⚠️ Leak" if p.get("cacheLeak") else "✅ Optimal"
        hit = int(p.get("cacheHitRate", 0.0) * 100)
        lines.append(
            f"| `{p.get('name', 'unknown')}` | ${p.get('costUSD', 0.0):,.2f} | {p.get('activeHours', 0.0):.1f}h | {hit}% | +${p.get('costSavedUSD', 0.0):,.2f} | {leak_icon} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 🛠️ Sources & Tool Distribution",
        "",
        f"- **Active Sources:** {', '.join(payload.get('sources', [])) or 'None detected'}",
        f"- **Total Sessions Analyzed:** {t.get('sessions', 0)}",
        f"- **Projects Tracked:** {t.get('projects', 0)}",
        "",
        "---",
        "*Report generated by [DevCity](https://github.com/sanjaydep1996/claude-code-usage-city) — Open Source Personal AI Developer Cockpit.*"
    ])

    return "\n".join(lines)


def write_report_file(payload: Dict[str, Any], out_path: str = "DEVCITY_REPORT.md") -> str:
    md = generate_markdown_report(payload)
    p = pathlib.Path(out_path)
    p.write_text(md, encoding="utf-8")
    return str(p.resolve())
